package main

import (
	"bufio"
	"fmt"
	"log"
	"os"
	"path/filepath"
)

type service struct {
	Uuid uint16 `yaml:"uuid"`
	Name string `yaml:"name"`
	Id   string `yaml:"id"`
}

const SERVICES_URL = "https://bitbucket.org/bluetooth-SIG/public/raw/main/assigned_numbers/uuids/service_uuids.yaml"

const SERVICES_TEMPLATE = `// Automatically generated by internal/generators/services.go
// ETag: {{ .Etag }}

package bt

type service struct {
	Id   string
	Name string
}

var services = map[uint16]service{
{{- range .Data }}
	{{ printf "0x%04X" .Uuid }}: {Id: "{{ .Id }}", Name: "{{ .Name }}"},
{{- end }}
}

func ServiceData(uuid uint16) (service, bool) {
	service, ok := services[uuid]
	return service, ok
}
`

func generateServices() {
	genFilepath := filepath.Join("..", "bt", "services.go")
	etag := fileEtag(genFilepath)
	data, changed := fetchData[service](etag, SERVICES_URL, "$.uuids")
	if !changed {
		fmt.Println("Services data hasn't changed, skipping...")
		return
	}

	f, err := os.Create(genFilepath)
	if err != nil {
		log.Fatalf("Error creating services.go file: %w", err)
	}
	defer f.Close()

	w := bufio.NewWriter(f)
	writeTemplate(SERVICES_TEMPLATE, data, w)
	w.Flush()
}
