package main

import (
	"bufio"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"text/template"

	"github.com/goccy/go-yaml"
)

type service struct {
	Uuid uint16 `yaml:"uuid"`
	Name string `yaml:"name"`
	Id   string `yaml:"id"`
}

const SERVICES_URL = "https://bitbucket.org/bluetooth-SIG/public/raw/main/assigned_numbers/uuids/service_uuids.yaml"

const SERVICES_TEMPLATE = `// Automatically generated by internal/generators/services.go

package bt

type service struct {
	Id   string
	Name string
}

var services = map[uint16]service{
{{- range . }}
	{{ printf "0x%04X" .Uuid }}: {Id: "{{ .Id }}", Name: "{{ .Name }}"},
{{- end }}
}

func ServiceData(uuid uint16) (service, bool) {
	service, ok := services[uuid]
	return service, ok
}
`

func fetchServices() (services []service) {
	resp, err := http.Get(SERVICES_URL)
	if err != nil {
		log.Fatal("Error fetching services page: %w", err)
	}
	defer resp.Body.Close()

	path, err := yaml.PathString("$.uuids")
	if err != nil {
		log.Fatalf("Error creating YAML path string: %w", err)
	}

	if err := path.Read(resp.Body, &services); err != nil {
		log.Fatalf("Error parsing services YAML: %w", err)
	}

	return services
}

func writeServices(services []service, wr io.Writer) {
	tmpl := template.Must(template.New("t").Parse(SERVICES_TEMPLATE))

	if err := tmpl.Execute(wr, services); err != nil {
		log.Fatalf("Error writing services template: %w", err)
	}
}

func generateServices() {
	services := fetchServices()

	f, err := os.Create(filepath.Join("..", "bt", "services.go"))
	if err != nil {
		log.Fatalf("Error creating services.go file: %w", err)
	}
	defer f.Close()

	w := bufio.NewWriter(f)
	writeServices(services, w)
	w.Flush()
}
