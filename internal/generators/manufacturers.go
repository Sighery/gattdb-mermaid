package main

import (
	"bufio"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/goccy/go-yaml"
)

type manufacturer struct {
	Id   uint16 `yaml:"value"`
	Name string `yaml:"name"`
}

const MANUFACTURERS_URL = "https://bitbucket.org/bluetooth-SIG/public/raw/main/assigned_numbers/company_identifiers/company_identifiers.yaml"

const MANUFACTURERS_TEMPLATE = `// Automatically generated by internal/generators/manufacturers.go

package bt

var manufacturers = map[uint16]string{
{{- range . }}
	{{ printf "0x%04X" .Id }}: "{{ escape .Name }}",
{{- end }}
}

func ManufacturerName(id uint16) (string, bool) {
	name, ok := manufacturers[id]
	return name, ok
}
`

func fetchManufacturers() (manufacturers []manufacturer) {
	resp, err := http.Get(MANUFACTURERS_URL)
	if err != nil {
		log.Fatalf("Error fetching manufacturers page: %w", err)
	}
	defer resp.Body.Close()

	path, err := yaml.PathString("$.company_identifiers")
	if err != nil {
		log.Fatalf("Error creating YAML path string: %w", err)
	}

	if err := path.Read(resp.Body, &manufacturers); err != nil {
		log.Fatal("Error parsing manufacturers YAML: %w", err)
	}

	return manufacturers
}

func writeManufacturers(manufacturers []manufacturer, wr io.Writer) {
	funcMap := template.FuncMap{
		// No native Go string escaping function. Only real worry is a sub double quote
		"escape": func(s string) string { return strings.ReplaceAll(s, `"`, `\"`) },
	}

	tmpl := template.Must(template.New("t").Funcs(funcMap).Parse(MANUFACTURERS_TEMPLATE))

	if err := tmpl.Execute(wr, manufacturers); err != nil {
		log.Fatalf("Error writing template to manufacturers.go file: %w", err)
	}
}

func generateManufacturers() {
	manufacturers := fetchManufacturers()

	f, err := os.Create(filepath.Join("..", "bt", "manufacturers.go"))
	if err != nil {
		log.Fatalf("Error creating manufacturers.go file: %w", err)
	}
	defer f.Close()

	w := bufio.NewWriter(f)

	writeManufacturers(manufacturers, w)

	w.Flush()
}
